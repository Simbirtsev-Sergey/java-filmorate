CREATE TABLE IF NOT EXISTS Ratings (
    rating_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL
);

CREATE TABLE IF NOT EXISTS Genres (
    genre_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL
);

CREATE TABLE IF NOT EXISTS Applications (
    application_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL
);

CREATE TABLE IF NOT EXISTS Users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(100) NOT NULL UNIQUE,
    login VARCHAR(100) NOT NULL UNIQUE,
    name VARCHAR(100),
    birthday DATE
);

CREATE TABLE IF NOT EXISTS Films (
    film_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    description VARCHAR(200),
    release_date DATE NOT NULL,
    duration INTEGER,
    rating_id BIGINT REFERENCES Ratings(rating_id)
);

CREATE TABLE IF NOT EXISTS Film_genres (
    film_id BIGINT REFERENCES Films(film_id) ON DELETE CASCADE,
    genre_id BIGINT REFERENCES Genres(genre_id),
    PRIMARY KEY (film_id, genre_id)
);

CREATE TABLE IF NOT EXISTS Film_likes (
    user_id BIGINT REFERENCES Users(user_id) ON DELETE CASCADE,
    film_id BIGINT REFERENCES Films(film_id) ON DELETE CASCADE,
    PRIMARY KEY (user_id, film_id)
);

CREATE TABLE IF NOT EXISTS Friendships (
    sender_id BIGINT NOT NULL REFERENCES Users(user_id) ON DELETE CASCADE,
    recipient_id BIGINT NOT NULL REFERENCES Users(user_id) ON DELETE CASCADE,
    application_id BIGINT REFERENCES Applications(application_id),
    PRIMARY KEY (sender_id, recipient_id)
);
